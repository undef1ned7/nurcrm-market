import React from "react";
import { useTranslation } from "react-i18next";
import { FormBlock } from "../formLayout";

const HOTKEY_GROUP_OPTIONS = Array.from({ length: 12 }, (_, index) => {
  const value = `F${index + 1}`;
  return { value, label: value };
});

/**
 * Компонент основной информации о товаре
 */
const ProductBasicInfo = ({
  newItemData,
  handleChange,
  marketData,
  handleMarketDataChange,
  generateBarcode,
  fieldErrors,
  itemType,
}) => {
  const { t } = useTranslation();
  const tp = (k: string): string => t(`crm.warehouse.addProduct.${k}`) as string;
  return (
    <div className="market-product-form__section">
      <h3 className="market-product-form__section-title">
        {tp("sectionBasic")}
      </h3>

      <div className="market-product-form__form-group">
        <label className="market-product-form__label">{tp("nameLabel")}</label>
        <input
          type="text"
          name="name"
          placeholder={tp("namePlaceholder")}
          className="market-product-form__input"
          value={newItemData.name}
          onChange={handleChange}
          required
        />
        {fieldErrors.name && (
          <p className="add-product-page__error">{fieldErrors.name}</p>
        )}
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-2 xl:grid-cols-4 gap-4">
        <FormBlock id="code">
          <div className="market-product-form__form-group">
            <label className="market-product-form__label">
              {itemType === "service" ? tp("serviceCode") : tp("productCode")}
            </label>
            <input
              type="text"
              className="market-product-form__input"
              value={marketData.code}
              readOnly
              placeholder={tp("autoGenerated")}
            />
          </div>
        </FormBlock>

        <FormBlock id="barcode">
          <div className="market-product-form__form-group">
            <label className="market-product-form__label">
              {tp("barcodeLabel")}{" "}
              <button
                type="button"
                className="market-product-form__generate-link"
                onClick={generateBarcode}
              >
                {tp("generateShort")}
              </button>
            </label>
            <input
              type="text"
              name="barcode"
              placeholder={tp("barcodePlaceholder")}
              className="market-product-form__input"
              value={newItemData.barcode}
              onChange={handleChange}
            />
            {fieldErrors.barcode && (
              <p className="add-product-page__error">{fieldErrors.barcode}</p>
            )}
          </div>
        </FormBlock>

        <FormBlock id="alternateBarcodes" className="col-span-full">
          <div className="market-product-form__form-group">
            <label className="market-product-form__label">
              {tp("altBarcodesLabel")}
            </label>
            <textarea
              className="market-product-form__input market-product-form__textarea"
              rows={3}
              placeholder={tp("altBarcodesPlaceholder")}
              value={marketData.alternateBarcodesText ?? ""}
              onChange={(e) =>
                handleMarketDataChange("alternateBarcodesText", e.target.value)
              }
            />
            <p className="market-product-form__hint">
              {tp("altBarcodesHint")}
            </p>
          </div>
        </FormBlock>

        <FormBlock id="article" className="col-span-full xl:col-span-1">
          <div className="market-product-form__form-group">
            <label className="market-product-form__label">
              {tp("articleLabel")}
            </label>
            <input
              type="text"
              placeholder={tp("articlePlaceholder")}
              className="market-product-form__input"
              value={marketData.article}
              onChange={(e) =>
                handleMarketDataChange("article", e.target.value)
              }
            />
          </div>
        </FormBlock>

        <FormBlock id="hotkey" className="col-span-full xl:col-span-1">
          <div className="market-product-form__form-group">
            <label className="market-product-form__label">
              {tp("hotkeyLabel")}
            </label>
            <select
              className="market-product-form__input"
              value={marketData.hotkeyGroup || ""}
              onChange={(e) =>
                handleMarketDataChange("hotkeyGroup", e.target.value)
              }
            >
              <option value="">{tp("hotkeyNone")}</option>
              {HOTKEY_GROUP_OPTIONS.map((option) => (
                <option key={option.value} value={option.value}>
                  {option.label}
                </option>
              ))}
            </select>
          </div>
        </FormBlock>
      </div>
    </div>
  );
};

export default React.memo(ProductBasicInfo);

