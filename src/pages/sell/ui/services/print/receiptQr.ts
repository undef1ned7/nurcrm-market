/** ESC/POS QR (GS ( k) */

import { ESC } from "./bytes";

export function buildEscPosQr(text: unknown) {
  const value = String(text || "").trim();
  if (!value) return [];
  const utf8 = new TextEncoder().encode(value);
  const len = utf8.length + 3;
  const pL = len & 0xff;
  const pH = (len >> 8) & 0xff;
  return [
    ESC(0x1d, 0x28, 0x6b, 0x03, 0x00, 0x31, 0x45, 0x30),
    ESC(0x1d, 0x28, 0x6b, 0x03, 0x00, 0x31, 0x43, 0x06),
    new Uint8Array([0x1d, 0x28, 0x6b, pL, pH, 0x31, 0x50, 0x30, ...utf8]),
    ESC(0x1d, 0x28, 0x6b, 0x03, 0x00, 0x31, 0x51, 0x30),
  ];
}
